import test from 'node:test';
import assert from 'node:assert/strict';
import {fixture} from './support/http.mjs';

test('dos jugadores comparten la cola, el audio privado y la posición de reproducción',async t=>{
  const f=fixture(t);
  const host=f.player(), guest=f.player(), outside=f.player();
  for(const [client,nick] of [[host,'Gian'],[guest,'Ana'],[outside,'Luz']]) await client.hit('session',{nick});
  const room=(await host.hit('rooms',{name:'DJ'})).data.room.code;
  const bytes=Buffer.from('RIFF0000WAVEfmt audio para la prueba');
  const path='/api/music/upload?room='+room+'&title=Desde%20mi%20PC&duration=180';
  let res=await host.request(path,bytes,{'content-type':'audio/wav'});
  assert.equal(res.statusCode,200);res.resume();
  let view=(await guest.hit('join',{code:room})).data.room;
  const first=view.music.queue[0];
  assert.equal(first.title,'Desde mi PC');
  assert.equal(first.addedBy,'Gian');
  assert.ok(view.music.startedAt<=view.music.serverNow);
  assert.equal(view.members.length,2);
  assert.equal(first.file,undefined);
  const url='/api/music/file?room='+room+'&id='+first.id;
  res=await guest.request(url,undefined,{range:'bytes=4-11'});
  assert.equal(res.statusCode,206);
  const parts=[];for await(const chunk of res)parts.push(chunk);
  assert.deepEqual(Buffer.concat(parts),bytes.subarray(4,12));
  assert.equal((await outside.request(url)).statusCode,403);
  const station={room,stationId:'mambo-inn'};
  assert.equal((await guest.hit('music/add',station)).status,200);
  assert.equal((await guest.hit('music/add',{...station,stationId:'desconocida'})).status,400);
  assert.equal((await guest.hit('music/next',{room:'OTR000',id:first.id})).status,403);
  await Promise.all([host,guest].map(c=>c.hit('music/ended',{room,id:first.id})));
  view=(await guest.hit('session')).data.room;
  assert.deepEqual(view.music.queue.map(x=>x.title),['Mambo INN · Lima']);
  assert.equal((await guest.request(url)).statusCode,404);
  await host.hit('leave',{});
  assert.equal((await host.request(url)).statusCode,403);
  const radio = view.music.queue[0];
  assert.equal(radio.duration,1800);
  assert.equal(radio.kind,'radio');
  await guest.hit('music/ended',{room,id:radio.id});
  assert.equal((await guest.hit('session')).data.room.music.queue.length,1);
  await guest.hit('music/next',{room,id:radio.id});
  assert.deepEqual((await guest.hit('session')).data.room.music.queue,[]);
});
